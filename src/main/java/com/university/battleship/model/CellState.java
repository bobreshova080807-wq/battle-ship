package com.university.battleship.model;

/**
 * Состояние клетки на поле.
 *
 * <p>Используется как в физическом поле ({@link Board}),
 * так и в карте знаний игрока ({@link Knowledge}).
 *
 * <p>Состояния делятся на три группы:
 * <ul>
 *   <li>Исходные: WATER, SHIP, SUBMARINE, MINE, MINESWEEPER</li>
 *   <li>После выстрела: MISS, HIT, SUNK, MINE_EXPLODED</li>
 *   <li>Специальные: CLEARED (обезврежена тральщиком)</li>
 * </ul>
 */
public enum CellState {
    /** Клетка пуста (вода), не обстреляна */
    WATER,

    /** В клетке находится корабль (не обстрелян) */
    SHIP,

    /** В клетке находится подводная лодка (скрыта от обычных выстрелов) */
    SUBMARINE,

    /** В клетке находится мина (скрыта) */
    MINE,

    /** В клетке находится тральщик (корабль, обезвреживающий мины) */
    MINESWEEPER,

    /** Промах — выстрел в воду */
    MISS,

    /** Попадание в корабль (корабль ещё не потоплен) */
    HIT,

    /** Корабль в клетке потоплен (все клетки поражены) */
    SUNK,

    /** Мина взорвалась */
    MINE_EXPLODED,

    /** Клетка обезврежена тральщиком */
    CLEARED
}
